from __future__ import annotations

import argparse
import json
from pathlib import Path

from geomind.runners.policy_runtime import try_save_trajectory_video


def main() -> int:
    parser = argparse.ArgumentParser(description="Replay trajectory trace and export a simple visualization video.")
    parser.add_argument("--trace-json", required=True, help="Path to trace.json generated by run_env_policy/run_suite.")
    parser.add_argument("--output-video", default="", help="Output gif path, defaults to sibling trajectory_replay.gif.")
    parser.add_argument("--fps", type=int, default=10)
    args = parser.parse_args()

    trace_path = Path(args.trace_json)
    trace = json.loads(trace_path.read_text(encoding="utf-8"))
    if not isinstance(trace, list):
        raise ValueError(f"Trace payload must be a list, got: {type(trace)!r}")
    output_path = Path(args.output_video) if args.output_video else trace_path.parent / "trajectory_replay.gif"
    status = try_save_trajectory_video(trace=trace, output_path=output_path, fps=int(args.fps))
    print(json.dumps(status, ensure_ascii=False, indent=2))
    if status.get("saved"):
        print(f"replay_video={output_path}")
        return 0
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
